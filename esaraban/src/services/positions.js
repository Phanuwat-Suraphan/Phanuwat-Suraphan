const ALL = SCHOOL_POSITIONS.flatMap((g) => g.items);
export const isKnownPosition = (value) => ALL.includes(String(value || '').trim());

/**
 * ช่องเลือกตำแหน่งที่ยังพิมพ์เองได้ — ใช้ <datalist> ไม่ใช่ <select>
 *
 * เลือกแบบนี้เพราะ <select> จะปิดกั้นตำแหน่งเฉพาะของแต่ละโรงเรียนที่ไม่มีในรายการ ส่วน <datalist>
 * ขึ้นรายการให้เลือกเหมือน dropdown แต่ยังพิมพ์คำอื่นได้ และค่าที่มีอยู่แล้วในฐานข้อมูล (ซึ่งพิมพ์กันเอง
 * มาก่อนหน้านี้) ก็ไม่หายไปจากฟอร์มเวลาเปิดมาแก้
 */
export function positionInput({ id = '', name = '', value = '', listId = 'schoolPositions' } = {}) {
  return `<input type="text" ${id ? `id="${id}"` : ''} ${name ? `name="${name}"` : ''}
    value="${escapeAttr(value)}" list="${listId}" placeholder="เลือกจากรายการ หรือพิมพ์เอง" />
    ${positionDatalist(listId)}`;
}

export function positionDatalist(listId = 'schoolPositions') {
  return `<datalist id="${listId}">${SCHOOL_POSITIONS.map((g) => g.items
    .map((p) => `<option value="${escapeAttr(p)}">${escapeAttr(g.group)}</option>`).join('')).join('')}</datalist>`;
}

function escapeAttr(s) {
  return String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
