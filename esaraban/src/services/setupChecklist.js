// รายการสิ่งที่ต้องตั้งค่าก่อนเปิดใช้งานจริง — สำหรับผู้ดูแลระบบของโรงเรียนที่เพิ่งติดตั้ง
//
// ทำไมต้องมี: ตอนติดตั้งจริงมีเรื่องต้องทำหลายอย่างที่กระจายอยู่คนละหน้า และไม่มีอะไรบอกว่า "เหลืออะไร
// อีกบ้าง" หรือ "ตอนนี้ปลอดภัยพอจะเอาหนังสือจริงเข้าหรือยัง" ผู้ดูแลจึงต้องจำเอง แล้วก็ลืม — ที่เจ็บที่สุด
// คือลืมปิดโหมดทดสอบ และไม่รู้ว่าข้อมูลยังไม่มีที่สำรอง จนกระทั่งข้อมูลหายไปแล้วถึงได้รู้
//
// รวมมาไว้ที่เดียวเป็นรายการติ๊ก เรียงตาม "ถ้าพลาดแล้วเสียหายแค่ไหน" ไม่ใช่ตามลำดับที่ทำ
// และหายไปเองเมื่อครบทุกข้อ ไม่ต้องมีปุ่มปิด — รายการที่ต้องกดปิดเองจะถูกกดปิดทั้งที่ยังไม่ได้ทำ
import { db, TEST_MODE_ON } from '../db.js';
import { getBackupStatus } from './dbBackup.js';
import { isLineNotifyConfigured } from './lineNotify.js';
import { schoolName } from './settings.js';

const DEFAULT_SCHOOL_NAME = 'โรงเรียนวัดเสาหิน';

/**
 * คืนรายการงานที่ยังไม่เสร็จ พร้อมระดับความสำคัญ
 *
 * blocking = ถ้ายังไม่ทำ ห้ามเอาหนังสือจริงเข้าระบบ (ข้อมูลหาย/ใครก็เข้าเป็นใครก็ได้)
 * ส่วนที่เหลือคือทำแล้วดีขึ้น แต่ไม่ทำก็ใช้งานได้
 */
export function setupChecklist() {
  const items = [];

  // 1) โหมดทดสอบ — ร้ายแรงที่สุด เพราะทุกคนใช้รหัสเดียวกัน และรหัสที่ตั้งเองถูกล้างทุกครั้งที่ restart
  if (TEST_MODE_ON) {
    items.push({
      key: 'test_mode', blocking: true, title: 'ปิดโหมดทดสอบ',
      detail: 'ตอนนี้ทุกบัญชีใช้รหัสผ่านเดียวกัน ใครเดารหัสนี้ได้จะเข้าเป็นใครก็ได้ในโรงเรียน และรหัสที่แต่ละคนตั้งเองจะถูกล้างทุกครั้งที่เซิร์ฟเวอร์เริ่มทำงาน',
      action: 'ลบตัวแปร TEST_MODE_PASSWORD ออกจากเซิร์ฟเวอร์แล้ว restart',
    });
  }

  // 2) ที่สำรองข้อมูล — บนโฮสต์ที่ดิสก์ไม่ถาวร ไม่มีสำรอง = ข้อมูลหายแน่นอน ไม่ใช่แค่อาจจะ
  const backup = getBackupStatus();
  if (backup.state === 'off') {
    items.push({
      key: 'backup', blocking: Boolean(backup.ephemeral), title: 'ตั้งค่าสำรองข้อมูลขึ้น Google Drive',
      detail: backup.ephemeral
        ? 'เซิร์ฟเวอร์นี้ใช้ดิสก์ชั่วคราว ข้อมูลทั้งหมดจะถูกล้างทุกครั้งที่ deploy หรือเซิร์ฟเวอร์รีสตาร์ท และเครื่องแบบฟรีจะหลับเองแล้วตื่นใหม่วันละหลายครั้ง'
        : 'ถ้าดิสก์ของเครื่องนี้เสียหาย ทะเบียนหนังสือทั้งเล่มจะไม่มีสำเนาให้กู้คืน',
      action: 'เชื่อมต่อที่หน้า เชื่อมต่อ Google Drive', href: '/admin/google-drive',
    });
  } else if (backup.state === 'warn') {
    items.push({
      key: 'backup_failing', blocking: false, title: 'การสำรองข้อมูลมีปัญหา',
      detail: 'เชื่อมต่อไว้แล้ว แต่การสำรองล่าสุดไม่สำเร็จหรือเงียบไปนานผิดปกติ',
      action: 'ดูรายละเอียดที่หน้าสำเนาสำรองข้อมูล', href: '/admin/backups',
    });
  }

  // 3) ชื่อโรงเรียน — ไปขึ้นบนหัวหนังสือราชการและตราประทับทุกใบ ผิดแล้วแก้ย้อนหลังไม่ได้
  if (schoolName() === DEFAULT_SCHOOL_NAME) {
    items.push({
      key: 'school_name', blocking: false, title: 'ตรวจชื่อโรงเรียนให้ถูกต้อง',
      detail: `ตอนนี้ใช้ค่าตั้งต้น "${DEFAULT_SCHOOL_NAME}" ซึ่งจะไปขึ้นบนหัวหนังสือ ตราประทับในไฟล์ PDF และแบบฟอร์มใบลาทุกใบ`,
      action: 'แก้ที่หน้าตั้งค่าโรงเรียน', href: '/admin/settings',
    });
  }

  // 4) บุคลากร — ระบบที่มีแต่บัญชีตัวอย่างยังไม่ได้เริ่มใช้งานจริง
  const realUsers = db.prepare(`
    SELECT COUNT(*) c FROM users
    WHERE deleted_at IS NULL AND status = 'active' AND employee_code NOT IN ('admin','director01','vicedir01','head_acad','reg001','teacher001')
  `).get().c;
  if (realUsers === 0) {
    items.push({
      key: 'users', blocking: false, title: 'เพิ่มบุคลากรจริงของโรงเรียน',
      detail: 'ตอนนี้มีแต่บัญชีตัวอย่างที่ระบบสร้างให้ — ส่งลิงก์หน้าลงทะเบียนให้ครูกรอกเองได้ แล้วมากดอนุมัติที่หน้าคำขอลงทะเบียน',
      action: 'เปิดหน้าคำขอลงทะเบียนเพื่อคัดลอกลิงก์', href: '/admin/registrations',
    });
  }

  // 5) แจ้งเตือนเข้าไลน์ — ไม่ตั้งก็ใช้ได้ทุกอย่าง แค่ครูต้องเปิดเว็บมาดูเอง
  if (!isLineNotifyConfigured()) {
    items.push({
      key: 'line', blocking: false, title: 'เชื่อมแจ้งเตือนเข้าไลน์ (ไม่บังคับ)',
      detail: 'ไม่เชื่อมก็ใช้งานได้ครบทุกอย่าง แต่ครูต้องเปิดเว็บเข้ามาดูเองว่ามีหนังสือรออยู่ไหม',
      action: 'ตั้งค่าที่หน้าแจ้งเตือนเข้าไลน์', href: '/admin/line',
    });
  }

  return {
    items,
    blocking: items.filter((i) => i.blocking).length,
    // พร้อมใช้งานจริง = ไม่มีข้อที่ทำให้ข้อมูลหายหรือใครก็เข้าเป็นใครก็ได้เหลืออยู่
    readyForRealUse: items.every((i) => !i.blocking),
  };
}
